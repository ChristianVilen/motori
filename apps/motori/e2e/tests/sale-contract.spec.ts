import { expect, test } from "../fixtures";
import { CONTRACT_LISTING_ID, CONTRACT_LISTING_SLUG, SEEDED_LISTING_ID } from "../global-setup";
import { waitForHydration } from "../helpers";

test("public sale contract stays local, restores edits and prints the preview", async ({
	page,
}) => {
	const marker = "ContractPrivateMarker748";
	const requests: string[] = [];
	page.on("request", (request) => requests.push(`${request.url()} ${request.postData() ?? ""}`));
	await page.goto("/kauppakirja");
	await waitForHydration(page);
	await expect(page.locator("#vehicle-make")).toHaveValue("");
	await page.goto(`/kauppakirja?ilmoitus=${CONTRACT_LISTING_ID}`);
	await waitForHydration(page);
	await expect(page.locator("#vehicle-make")).toHaveValue("Honda");
	await page.goto(`/pyorat/myynti/${CONTRACT_LISTING_ID}/${CONTRACT_LISTING_SLUG}`);
	await waitForHydration(page);
	await page.getByRole("link", { name: "Tee kauppakirja", exact: true }).click();
	await expect(page).toHaveURL(/\/kauppakirja\?ilmoitus=/);
	const contractUrl = page.url();
	await expect(page.locator("#vehicle-make")).toHaveValue("Honda");
	await expect(page.locator("#vehicle-model")).toHaveValue("CB500F");
	await expect(page.locator("#vehicle-year")).toHaveValue("2022");
	await expect(page.locator("#vehicle-mileage")).toHaveValue("12345");
	await expect(page.locator("#vehicle-power")).toHaveValue("35 kW (48 hv)");
	await expect(page.locator("#sale-price")).toHaveValue("4500,50");
	await expect(page.locator("#seller-lastName")).toHaveValue("");
	await page.locator("#seller-lastName").fill(marker);
	await page.locator("#buyer-firstNames").fill(`${marker}Buyer`);
	await page.locator("#seller-lastName").press("Enter");
	await page.reload();
	await waitForHydration(page);
	await expect(page.locator("#seller-lastName")).toHaveValue(marker);
	await page.getByRole("button", { name: "Esikatselu", exact: true }).click();
	const document = page.getByTestId("contract-document");
	await expect(document).toContainText(marker);
	await expect(document.getByRole("button", { name: /^Poista Myyjä$/ })).toHaveCount(0);
	await page.getByRole("button", { name: "Poista Ajoneuvo on velaton." }).click();
	await expect(page.getByRole("button", { name: "Palauta Ajoneuvo on velaton." })).toBeVisible();
	await page.emulateMedia({ media: "print" });
	await expect(page.getByRole("button", { name: "Palauta Ajoneuvo on velaton." })).toBeHidden();
	await expect(document.getByText("Ajoneuvo on velaton.", { exact: true })).toBeHidden();
	await expect(document.getByText("Myyjä omistaa ajoneuvon.", { exact: true })).toBeVisible();
	await expect(page.getByRole("navigation").first()).toBeHidden();
	await expect(document).toContainText("Motori ei ole kaupan osapuoli.");
	await page.emulateMedia({ media: "screen" });
	await page.getByRole("button", { name: "Palauta Ajoneuvo on velaton." }).click();
	await expect(document.getByText("Ajoneuvo on velaton.", { exact: true })).toBeVisible();
	await page.getByRole("button", { name: "Tyhjennä lomake", exact: true }).click();
	await page.reload();
	await waitForHydration(page);
	await expect(page.locator("#seller-lastName")).toHaveValue("");
	await expect(page.locator("#vehicle-make")).toHaveValue("");
	await expect(page.locator("#sale-price")).toHaveValue("");
	await expect(page).toHaveURL(contractUrl);
	await page.goto(`/kauppakirja?ilmoitus=${SEEDED_LISTING_ID}`);
	await waitForHydration(page);
	await expect(page.locator("#vehicle-make")).toHaveValue("");
	await page.goto("/kauppakirja?ilmoitus=unknown1");
	await waitForHydration(page);
	await expect(page.locator("#vehicle-make")).toHaveValue("");
	await expect(page.locator('link[rel="canonical"]')).toHaveAttribute("href", /\/kauppakirja$/);
	expect(requests.some((request) => request.includes(marker))).toBe(false);
});
